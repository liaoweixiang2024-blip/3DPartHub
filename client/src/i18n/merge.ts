function toTraditionalText(value: string) {
  let next = value;
  Object.entries(TRADITIONAL_PHRASE_MAP).forEach(([from, to]) => {
    next = next.replaceAll(from, to);
  });
  return Array.from(next)
    .map((char) => TRADITIONAL_CHAR_MAP[char] || char)
    .join('');
}

export function convertTranslationText(value: TranslationMap): TranslationMap {
  return Object.fromEntries(
    Object.entries(value).map(([key, item]) => [
      key,
      typeof item === 'string'
        ? toTraditionalText(item)
        : Array.isArray(item)
          ? item.map((text) => toTraditionalText(text))
          : convertTranslationText(item),
    ]),
  );
}
