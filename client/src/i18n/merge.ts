// 翻译合并与简繁转换工具（从 resources.ts 抽出）
export type TranslationMap = {
  [key: string]: string | string[] | TranslationMap;
};

export function mergeTranslation(base: TranslationMap, overrides: TranslationMap): TranslationMap {
  const merged: TranslationMap = { ...base };
  Object.entries(overrides).forEach(([key, value]) => {
    const baseValue = merged[key];
    if (
      value &&
      typeof value === 'object' &&
      !Array.isArray(value) &&
      baseValue &&
      typeof baseValue === 'object' &&
      !Array.isArray(baseValue)
    ) {
      merged[key] = mergeTranslation(baseValue as TranslationMap, value as TranslationMap);
      return;
    }
    merged[key] = value;
  });
  return merged;
}

